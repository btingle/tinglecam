"""Sort Onshape STEP exports of the jig tabs into one file per jig and role, by body name alone.

    python3 sort_exports.py OUT_DIR EXPORT.step [EXPORT.step ...] [--laser-gap MM]

Body names are "<type> <op> <role>": type is the track (op1, op2) or species (glue, op0), e.g.
"sL op1 jaw A (fixed)", "slr op0 part", "lrrl glue guide 2". Each (type, op) is a jig; its bodies go to
OUT_DIR/G-0/<species>/ (glue, op0) or OUT_DIR/1-2/<track>/ (op1, op2) as "<type> <op> <class>.step", class
being fixture (jaws, plate, acrylic layers), stock or part. Each jig is centred on its fixture's plan
bounding box (z unchanged), which undoes the features' "Move result" offsets. The glue-up's wood blanks
become laser DXFs instead: each sheet's empty channels (the webs) are closed so outlines touch (or sit
--laser-gap apart) in the glue-up's arrangement, one file for the fixture-hole sheet and one for the plain sheets.
--lattice species (default lrrl) instead get every blank as one shape (flip the mirrored ones over) in the
densest lattice that fits the --board width (default 6 x 24 in). A machining jig whose mirror-image track
is missing (L/R, sL/sR, Ls/Rs, RL/LR, slr/srl) is generated by mirroring across the YZ plane. Local only:
no API calls.
"""
import os
import re
import sys
from collections import defaultdict
from contextlib import contextmanager
from pathlib import Path

NAME = re.compile(r"^(?P<who>\S+) (?P<op>glue|op0|op1|op2) (?P<role>.+)$")
MIRRORS = {"L": "R", "sL": "sR", "Ls": "Rs", "RL": "LR", "slr": "srl"}
MIRRORS.update({v: k for k, v in MIRRORS.items()})


def read_named_solids(path):
    """[(name, solid)] from a STEP file, assemblies flattened with their placements applied."""
    from OCP.IFSelect import IFSelect_RetDone
    from OCP.STEPCAFControl import STEPCAFControl_Reader
    from OCP.TCollection import TCollection_ExtendedString
    from OCP.TDataStd import TDataStd_Name
    from OCP.TDF import TDF_Label, TDF_LabelSequence
    from OCP.TDocStd import TDocStd_Document
    from OCP.TopAbs import TopAbs_SOLID
    from OCP.TopExp import TopExp_Explorer
    from OCP.XCAFDoc import XCAFDoc_DocumentTool

    doc = TDocStd_Document(TCollection_ExtendedString("step"))
    reader = STEPCAFControl_Reader()
    reader.SetNameMode(True)
    if reader.ReadFile(str(path)) != IFSelect_RetDone or not reader.Transfer(doc):
        raise SystemExit(f"could not read {path}")
    tool = XCAFDoc_DocumentTool.ShapeTool_s(doc.Main())

    def name(label):
        attr = TDataStd_Name()
        return attr.Get().ToExtString() if label.FindAttribute(TDataStd_Name.GetID_s(), attr) else ""

    out = []

    def walk(label, inherited):
        own = name(label)
        if tool.IsComponent_s(label):
            ref = TDF_Label()
            if tool.GetReferredShape_s(label, ref) and tool.IsAssembly_s(ref):
                walk(ref, own or inherited)
                return
            own = name(ref) or own
        if tool.IsAssembly_s(label):
            comps = TDF_LabelSequence()
            tool.GetComponents_s(label, comps)
            for i in range(1, comps.Length() + 1):
                walk(comps.Value(i), own or inherited)
            return
        explorer = TopExp_Explorer(tool.GetShape_s(label), TopAbs_SOLID)
        while explorer.More():
            out.append((own or inherited, explorer.Current()))
            explorer.Next()

    free = TDF_LabelSequence()
    tool.GetFreeShapes(free)
    for i in range(1, free.Length() + 1):
        walk(free.Value(i), "")
    return out


def top_face(solid):
    """The highest face facing +z (a blank sheet's plan outline, holes included)."""
    from OCP.BRepAdaptor import BRepAdaptor_Surface
    from OCP.GeomAbs import GeomAbs_Plane
    from OCP.TopAbs import TopAbs_FACE
    from OCP.TopExp import TopExp_Explorer
    from OCP.TopoDS import TopoDS

    best, best_z = None, -float("inf")
    explorer = TopExp_Explorer(solid, TopAbs_FACE)
    while explorer.More():
        face = TopoDS.Face_s(explorer.Current())
        surface = BRepAdaptor_Surface(face)
        if surface.GetType() == GeomAbs_Plane:
            ax = surface.Plane().Axis()
            if abs(abs(ax.Direction().Z()) - 1) < 1e-9 and ax.Location().Z() > best_z:
                best, best_z = face, ax.Location().Z()
        explorer.Next()
    return best


def face_wires(face):
    """[(is_outer, [edge curves as ('circle', (cx, cy), r) or ('points', [(x, y), ...])])]"""
    from OCP.BRepAdaptor import BRepAdaptor_Curve
    from OCP.BRepTools import BRepTools, BRepTools_WireExplorer
    from OCP.GCPnts import GCPnts_QuasiUniformDeflection
    from OCP.GeomAbs import GeomAbs_Circle
    from OCP.TopAbs import TopAbs_REVERSED, TopAbs_WIRE
    from OCP.TopExp import TopExp_Explorer
    from OCP.TopoDS import TopoDS

    outer = BRepTools.OuterWire_s(face)
    wires = []
    explorer = TopExp_Explorer(face, TopAbs_WIRE)
    while explorer.More():
        wire = TopoDS.Wire_s(explorer.Current())
        curves = []
        edges = BRepTools_WireExplorer(wire, face)
        while edges.More():
            edge = edges.Current()
            curve = BRepAdaptor_Curve(edge)
            if curve.GetType() == GeomAbs_Circle and abs(curve.LastParameter() - curve.FirstParameter() - 2 * 3.141592653589793) < 1e-6:
                c = curve.Circle()
                curves.append(("circle", (c.Location().X(), c.Location().Y()), c.Radius()))
            else:
                sampler = GCPnts_QuasiUniformDeflection(curve, 0.005)
                pts = [sampler.Value(i) for i in range(1, sampler.NbPoints() + 1)]
                pts = [(p.X(), p.Y()) for p in pts]
                curves.append(("points", pts[::-1] if edge.Orientation() == TopAbs_REVERSED else pts))
            edges.Next()
        wires.append((wire.IsSame(outer), curves))
        explorer.Next()
    return wires


def outline_polygon(wires):
    from shapely.geometry import Polygon

    pts = []
    for is_outer, curves in wires:
        if is_outer:
            for kind, *data in curves:
                pts += data[0] if kind == "points" else []
    return Polygon(pts).buffer(0)


def packed(polygons, gap):
    """Plan offsets that close the layout's empty straight channels (the glue-up webs) down to `gap`, in x then
    y, so pieces end up touching (or `gap` apart) but keep their arrangement."""
    offsets = [[0.0, 0.0] for _ in polygons]
    for axis in (0, 1):
        spans = []
        for i, poly in enumerate(polygons):
            lo, hi = poly.bounds[axis] + offsets[i][axis], poly.bounds[axis + 2] + offsets[i][axis]
            spans.append((lo, hi, i))
        spans.sort()
        shift, reach = 0.0, None
        for lo, hi, i in spans:
            if reach is not None and lo - reach > gap:
                shift += lo - reach - gap
            reach = hi if reach is None else max(reach, hi)
            offsets[i][axis] -= shift
    return offsets


def lattice_strip(outline, count, width, gap):
    """Pack `count` copies of one outline (turned, never mirrored) into the shortest strip `width` tall: the
    densest lattices of the shape, each tried at every 2 degree turn and height offset.
    Returns (turn in degrees, [(x, y)] centroid positions, strip length)."""
    import numpy as np
    from shapely import affinity
    from shapely.prepared import prep

    shape = affinity.translate(outline, -outline.centroid.x, -outline.centroid.y).simplify(0.05)
    body = shape.buffer(gap / 2, join_style=2) if gap else shape
    ready = prep(body)

    def overlaps(dx, dy):
        other = affinity.translate(body, dx, dy)
        return ready.intersects(other) and body.intersection(other).area > 1e-3

    def reach(u, others=((0.0, 0.0),)):
        """Shortest step along unit vector u clear of every copy at `others`."""
        def bad(t):
            return any(overlaps(t * u[0] - ox, t * u[1] - oy) for ox, oy in others)
        t = 0.0
        while bad(t):
            t += 1.0
        lo, hi = max(0.0, t - 1.0), t
        for _ in range(18):
            mid = (lo + hi) / 2
            lo, hi = (mid, hi) if bad(mid) else (lo, mid)
        return hi

    lattices = []
    for f1 in np.radians(np.arange(0, 180, 3.0)):
        u = np.array([np.cos(f1), np.sin(f1)])
        a = reach(u) * u
        row = [tuple(k * a) for k in range(-12, 13)]
        for f2 in f1 + np.radians(np.arange(9, 172, 3.0)):
            v = np.array([np.cos(f2), np.sin(f2)])
            b = reach(v, row) * v
            while True:  # Lagrange-Gauss reduction to the shortest basis of the same lattice
                if a @ a > b @ b:
                    a, b = b, a
                m = round((a @ b) / (a @ a))
                if m == 0:
                    break
                b = b - m * a
            if all(not overlaps(*(i * a + j * b)) for i in range(-3, 4) for j in range(0, 4) if j > 0 or i > 0):
                lattices.append((abs(a[0] * b[1] - a[1] * b[0]), a, b))
    lattices.sort(key=lambda t: t[0])
    ij = np.array([(i, j) for i in range(-40, 41) for j in range(-40, 41)], float)
    best = (float("inf"), 0.0, None)
    for _, a, b in lattices[:12]:
        for turn in range(0, 180, 2):
            c, s_ = np.cos(np.radians(turn)), np.sin(np.radians(turn))
            rot = np.array([[c, -s_], [s_, c]])
            pts = ij[:, :1] * (rot @ a) + ij[:, 1:] * (rot @ b)
            x0, y0, x1, y1 = affinity.rotate(body, turn, origin=(0, 0)).bounds
            for dy in np.linspace(0, 40, 41):
                y = pts[:, 1] + dy
                inside = pts[(y + y0 >= 0) & (y + y1 <= width)] + [0, dy]
                if len(inside) < count:
                    continue
                inside = inside[np.argsort(inside[:, 0])]
                spans = inside[count - 1:, 0] - inside[:len(inside) - count + 1, 0]
                k = int(np.argmin(spans))
                if spans[k] + x1 - x0 < best[0]:
                    chosen = inside[k:k + count] - [inside[k, 0] + x0, 0]
                    best = (spans[k] + x1 - x0, turn, chosen)
    length, turn, chosen = best
    return turn, [tuple(p) for p in chosen], length


def write_dxf(path, shapes):
    """shapes: [(wires, f)] with f mapping plan points; mm, everything on layer CUT."""
    import ezdxf

    doc = ezdxf.new()
    doc.units = ezdxf.units.MM
    msp = doc.modelspace()
    for wires, f in shapes:
        for _, curves in wires:
            for kind, *data in curves:
                if kind == "circle":
                    centre, r = data
                    msp.add_circle(f(centre), r, dxfattribs={"layer": "CUT"})
                else:
                    msp.add_lwpolyline([f(p) for p in data[0]], dxfattribs={"layer": "CUT"})
    doc.saveas(path)


def shifted(dx, dy):
    return lambda p: (p[0] + dx, p[1] + dy)


def placed(centre, turn, at):
    """Turn about `centre` by `turn` degrees, then move `centre` to `at`."""
    import math

    c, s = math.cos(math.radians(turn)), math.sin(math.radians(turn))
    return lambda p: (at[0] + c * (p[0] - centre[0]) - s * (p[1] - centre[1]),
                      at[1] + s * (p[0] - centre[0]) + c * (p[1] - centre[1]))


def write_laser(folder, who, named, gap, board, lattice):
    """Blank sheets -> packed laser DXFs. Normally one file for the fixture-hole sheet and one for the (identical)
    plain sheets, in the glue-up's arrangement with the webs closed. Species in `lattice` have one blank shape
    (mirror images are the same blank flipped over), so every blank of the jig is cut as that shape in one
    lattice-packed strip as tall as the board's short side."""
    sheets = defaultdict(list)
    for name, solid in named:
        sheets[name].append(face_wires(top_face(solid)))
    kinds = defaultdict(list)
    for name, outlines in sorted(sheets.items()):
        holes = sum(1 for wires in outlines for is_outer, _ in wires if not is_outer)
        kinds["fixture-hole sheet" if holes else "plain sheet"].append(outlines)
    if who in lattice:
        holed = kinds["fixture-hole sheet"][0][0]
        plain = [w for w in holed if w[0]]
        n_holed = len(kinds["fixture-hole sheet"][0])
        n_plain = sum(len(layer) for layer in kinds["plain sheet"])
        outline = outline_polygon(holed)
        centre = (outline.centroid.x, outline.centroid.y)
        turn, spots, length = lattice_strip(outline, n_holed + n_plain, board[0], gap)
        shapes = [(holed if i < n_holed else plain, placed(centre, turn, at)) for i, at in enumerate(spots)]
        label = f"{n_holed} fixture-hole + {n_plain} plain blanks"
        write_dxf(folder / f"{who} laser {label}.dxf", shapes)
        return [f"{label} (flip the mirrored ones) in {length:.0f} x {board[0]:g} mm, "
                f"{int(board[1] // length)} jig(s) per {board[0]:g} x {board[1]:g} board"]
    written = []
    for kind, layers in sorted(kinds.items()):
        outlines = layers[0]
        offsets = packed([outline_polygon(w) for w in outlines], gap)
        count = f" x{len(layers)}" if len(layers) > 1 else ""
        write_dxf(folder / f"{who} laser {kind}{count}.dxf", [(w, shifted(*o)) for w, o in zip(outlines, offsets)])
        written.append(f"{kind}{count}")
    return written


def classify(op, role):
    if op == "glue":
        return "blanks" if role.startswith("blank") else "fixture"
    return role if role in ("stock", "part") else "fixture"


def transformed(shape, trsf):
    from OCP.BRepBuilderAPI import BRepBuilderAPI_Transform

    return BRepBuilderAPI_Transform(shape, trsf, True).Shape()


def plan_centre(shapes):
    from OCP.Bnd import Bnd_Box
    from OCP.BRepBndLib import BRepBndLib

    box = Bnd_Box()
    for s in shapes:
        BRepBndLib.Add_s(s, box)
    x0, y0, _, x1, y1, _ = box.Get()
    return (x0 + x1) / 2, (y0 + y1) / 2


def centred(bodies):
    """Move a jig so its fixture's plan bounding box is centred on the origin."""
    from OCP.gp import gp_Trsf, gp_Vec

    fixture = [s for _, c, s in bodies if c == "fixture"] or [s for _, _, s in bodies]
    cx, cy = plan_centre(fixture)
    t = gp_Trsf()
    t.SetTranslation(gp_Vec(-cx, -cy, 0))
    return [(n, c, transformed(s, t)) for n, c, s in bodies]


def mirrored(bodies, who, twin):
    from OCP.gp import gp_Ax2, gp_Dir, gp_Pnt, gp_Trsf

    t = gp_Trsf()
    t.SetMirror(gp_Ax2(gp_Pnt(0, 0, 0), gp_Dir(1, 0, 0)))
    return [(twin + n[len(who):], c, transformed(s, t)) for n, c, s in bodies]


def write_step(path, named):
    """One STEP file, each solid keeping its name."""
    from OCP.IFSelect import IFSelect_RetDone
    from OCP.Interface import Interface_Static
    from OCP.STEPCAFControl import STEPCAFControl_Writer
    from OCP.STEPControl import STEPControl_AsIs
    from OCP.TCollection import TCollection_ExtendedString
    from OCP.TDataStd import TDataStd_Name
    from OCP.TDocStd import TDocStd_Document
    from OCP.XCAFDoc import XCAFDoc_DocumentTool

    doc = TDocStd_Document(TCollection_ExtendedString("step"))
    tool = XCAFDoc_DocumentTool.ShapeTool_s(doc.Main())
    for name, shape in named:
        TDataStd_Name.Set_s(tool.AddShape(shape, False), TCollection_ExtendedString(name))
    Interface_Static.SetCVal_s("write.step.unit", "MM")
    Interface_Static.SetCVal_s("write.step.schema", "AP214IS")
    writer = STEPCAFControl_Writer()
    writer.SetNameMode(True)
    with quiet():
        ok = writer.Transfer(doc, STEPControl_AsIs) and writer.Write(str(path)) == IFSelect_RetDone
    if not ok:
        raise SystemExit(f"could not write {path}")


@contextmanager
def quiet():
    """Open CASCADE prints transfer statistics straight to file descriptor 1."""
    sys.stdout.flush()
    saved = os.dup(1)
    with open(os.devnull, "w") as null:
        os.dup2(null.fileno(), 1)
        try:
            yield
        finally:
            os.dup2(saved, 1)
            os.close(saved)


def sort_exports(out_dir, paths, gap=0.0, board=(152.4, 609.6), lattice=("lrrl",)):
    jigs = defaultdict(list)
    source = {}
    for path in paths:
        found = defaultdict(list)
        for name, solid in read_named_solids(path):
            m = NAME.match(name)
            if not m:
                print(f"  skipped unrecognised body {name!r} in {Path(path).name}")
                continue
            found[(m["who"], m["op"])].append((name, classify(m["op"], m["role"]), solid))
        for key, bodies in found.items():
            if key in jigs:
                print(f"  {key[0]} {key[1]} is in both {source[key]} and {Path(path).name}; keeping the first")
                continue
            jigs[key] = centred(bodies)
            source[key] = Path(path).name
    for (who, op), bodies in list(jigs.items()):
        twin = MIRRORS.get(who)
        if op in ("op1", "op2") and twin and (twin, op) not in jigs:
            jigs[(twin, op)] = mirrored(bodies, who, twin)
            source[(twin, op)] = f"mirror of {who}"
    out = Path(out_dir)
    folders = {}
    for who, op in jigs:
        folder = out / ("G-0" if op in ("glue", "op0") else "1-2") / who
        clash = folders.setdefault(str(folder).lower(), folder)
        if clash != folder:
            raise SystemExit(f"{clash} and {folder} are the same folder on a case-insensitive drive; rename one type")
    for (who, op), bodies in sorted(jigs.items()):
        by_class = defaultdict(list)
        for name, cls, solid in bodies:
            by_class[cls].append((name, solid))
        folder = out / ("G-0" if op in ("glue", "op0") else "1-2") / who
        folder.mkdir(parents=True, exist_ok=True)
        report = []
        for cls, named in sorted(by_class.items()):
            if cls == "blanks":
                report.append("laser " + ", ".join(write_laser(folder, who, named, gap, board, lattice)))
            else:
                write_step(folder / f"{who} {op} {cls}.step", named)
                report.append(f"{cls} {len(named)}")
        print(f"{who} {op}: " + ", ".join(report) + f"  ({source[(who, op)]})")


if __name__ == "__main__":
    import argparse

    parser = argparse.ArgumentParser(usage=__doc__)
    parser.add_argument("out_dir")
    parser.add_argument("exports", nargs="+")
    parser.add_argument("--laser-gap", type=float, default=0.0, help="Gap between packed blank outlines (mm)")
    parser.add_argument("--board", default="152.4x609.6", help="Wood board WIDTHxLENGTH (mm), default 6 x 24 in")
    parser.add_argument("--lattice", nargs="*", default=["lrrl"], help="Species whose blanks are lattice-packed")
    args = parser.parse_args()
    board = tuple(sorted(float(v) for v in args.board.lower().split("x")))
    sort_exports(args.out_dir, args.exports, args.laser_gap, board, tuple(args.lattice))
